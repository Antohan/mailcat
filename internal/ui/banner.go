// MonthBanner — 5 строк ASCII-баннера месяца («НОЯБРЬ»). Неизвестные руны
// (исключены по построению: текст из russianMonths) рисуются пробелами.
func MonthBanner(month time.Month) []string {
	name := strings.ToUpper(russianMonths[month-1])
	rows := make([]string, 5)
	for row := 0; row < 5; row++ {
		parts := make([]string, 0, len(name))
		for _, r := range name {
			glyph, ok := bannerGlyphs[r]
			if !ok {
				glyph = [5]string{"    ", "    ", "    ", "    ", "    "}
			}
			parts = append(parts, glyph[row])
		}
		rows[row] = strings.Join(parts, " ")
	}
	return rows
}
