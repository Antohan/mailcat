package ui

// Тест отбрасывания устаревших ответов календаря (security-ревью этапа 4):
// при смене месяца приземлившийся ответ старого запроса не должен помечать
// текущий месяц загруженным и не должен подменять его события.

import "testing"

func TestMonthStale(t *testing.T) {
	if monthStale("2026-11", "2026-11") {
		t.Error("актуальный ответ помечен устаревшим")
	}
	if !monthStale("2026-11", "2026-12") {
		t.Error("ответ прошлого месяца не отброшен при смене на следующий")
	}
	if !monthStale("2026-12", "2026-11") {
		t.Error("ответ следующего месяца не отброшен при возврате")
	}
}
